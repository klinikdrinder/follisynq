/* Generates supabase/migrations/0003_seed_catalog.sql from src/lib/catalog.ts (compact JSON-driven seed) */
import { writeFileSync } from 'node:fs';
import { STAGES, DONOR_REGIONS, RECIPIENT_REGIONS, PATIENT_SECTIONS, RECORDING_CONTEXT, ParamDef } from '../src/lib/catalog';

const strip = (p: ParamDef) => ({ k: p.key, l: p.label, t: p.type, g: p.group, u: p.unit, o: p.options, p: p.provenance ? 1 : 0, s: p.searchable ? 1 : 0, h: p.help });
const data = {
  stages: STAGES.map((s) => ({ c: s.code, n: s.number, sl: s.slug, ti: s.title, d: s.description, f: s.folder, pr: s.priority, v: s.views ?? [],
    sub: s.subcategories.map((x) => [x.code, x.label, x.folder]), par: s.params.map(strip) })),
  other: [...PATIENT_SECTIONS.map((x) => ({ scope: `patient_${x.key}`, par: x.params.map(strip) })), { scope: 'recording_context', par: RECORDING_CONTEXT.map(strip) }],
  donor: DONOR_REGIONS, recipient: RECIPIENT_REGIONS,
};
const json = JSON.stringify(data).replace(/'/g, "''");
const sql = `-- Seed: organisation, branches, roles and clinical catalogue (generated by scripts/gen-seed.ts). NO patient records.
insert into public.staff_roles (code, label, description) values
  ('admin','Administrator','Manage staff, branches, catalogues, devices, exports and audit logs'),
  ('doctor','Doctor','Create and manage cases, record media, enter procedural parameters'),
  ('nurse','Clinical assistant / nurse','Record media, enter authorised clinical information, assist documentation')
on conflict (code) do nothing;
insert into public.organizations (id, name, short_code, settings) values
  ('6b1f0c7e-0d5a-4b5e-9a51-6c1f1d9e0001','Klinik Dr Inder','KDI',
   '{"inactivity_lock_minutes":10,"offline_auth_hours":72,"storage_warn_pct":80,"storage_critical_pct":92,"consent_version":"KDI-CONSENT-v1","backup_reminder_hours":24,"retention_years":7}'::jsonb)
on conflict (id) do nothing;
insert into public.clinic_branches (org_id, code, name) values
  ('6b1f0c7e-0d5a-4b5e-9a51-6c1f1d9e0001','PJ','Petaling Jaya'),
  ('6b1f0c7e-0d5a-4b5e-9a51-6c1f1d9e0001','SUBANG','Subang Jaya')
on conflict do nothing;
do $seed$
declare
  org uuid := '6b1f0c7e-0d5a-4b5e-9a51-6c1f1d9e0001';
  d jsonb := '${json}'::jsonb;
  st jsonb; sb jsonb; pr jsonb; oth jsonb; sid uuid; i int; r text;
begin
  for st in select * from jsonb_array_elements(d->'stages') loop
    insert into public.procedure_stages (org_id, code, number, slug, title, description, folder_name, priority, standard_views, sort_order)
    values (org, st->>'c', (st->>'n')::int, st->>'sl', st->>'ti', st->>'d', st->>'f', st->>'pr',
            array(select jsonb_array_elements_text(st->'v')), (st->>'n')::int)
    on conflict (org_id, code) do nothing;
    select id into sid from public.procedure_stages where org_id = org and code = st->>'c';
    i := 0;
    for sb in select * from jsonb_array_elements(st->'sub') loop
      i := i + 1;
      insert into public.procedure_subcategories (org_id, stage_id, code, label, folder_name, sort_order)
      values (org, sid, sb->>0, sb->>1, sb->>2, i) on conflict (stage_id, code) do nothing;
    end loop;
    i := 0;
    for pr in select * from jsonb_array_elements(st->'par') loop
      i := i + 1;
      insert into public.parameter_definitions (org_id, scope, stage_id, key, label, data_type, group_name, unit, options, provenance, searchable, help, sort_order)
      values (org, 'stage', sid, pr->>'k', pr->>'l', pr->>'t', pr->>'g', pr->>'u', pr->'o', (pr->>'p')::int = 1, (pr->>'s')::int = 1, pr->>'h', i)
      on conflict do nothing;
    end loop;
  end loop;
  for oth in select * from jsonb_array_elements(d->'other') loop
    i := 0;
    for pr in select * from jsonb_array_elements(oth->'par') loop
      i := i + 1;
      insert into public.parameter_definitions (org_id, scope, stage_id, key, label, data_type, group_name, unit, options, provenance, searchable, help, sort_order)
      values (org, oth->>'scope', null, pr->>'k', pr->>'l', pr->>'t', pr->>'g', pr->>'u', pr->'o', (pr->>'p')::int = 1, (pr->>'s')::int = 1, pr->>'h', i)
      on conflict do nothing;
    end loop;
  end loop;
  i := 0;
  for r in select * from jsonb_array_elements_text(d->'donor') loop
    i := i + 1;
    insert into public.anatomical_regions (org_id, kind, code, label, sort_order)
    values (org, 'donor', trim(both '_' from regexp_replace(upper(r), '[^A-Z0-9]+', '_', 'g')), r, i) on conflict do nothing;
  end loop;
  i := 0;
  for r in select * from jsonb_array_elements_text(d->'recipient') loop
    i := i + 1;
    insert into public.anatomical_regions (org_id, kind, code, label, sort_order)
    values (org, 'recipient', trim(both '_' from regexp_replace(upper(r), '[^A-Z0-9]+', '_', 'g')), r, i) on conflict do nothing;
  end loop;
end $seed$;
`;
writeFileSync(new URL('../supabase/migrations/0003_seed_catalog.sql', import.meta.url), sql);
console.log('seed written', sql.length, 'bytes');
